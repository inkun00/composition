import { createHash } from "node:crypto";
import { cp, mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build, loadEnv } from "vite";
import { zipSync } from "fflate";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const artifacts = path.join(root, "artifacts");
const packageName = "maeum-melody-portable";
const output = path.join(artifacts, packageName);
const markerName = "package.generated.json";
const portableSources = path.join(root, "scripts", "portable");
const mimeTypes = new Map([
  [".png", "image/png"],
  [".webp", "image/webp"],
  [".svg", "image/svg+xml"],
  [".wav", "audio/wav"],
  [".mp3", "audio/mpeg"],
  [".ogg", "audio/ogg"],
  [".json", "application/json"]
]);

async function filesWithin(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = await Promise.all(entries.map(async (entry) => {
    const absolute = path.join(directory, entry.name);
    if (entry.isDirectory()) return filesWithin(absolute);
    if (!entry.isFile()) throw new Error(`Unsupported package entry: ${absolute}`);
    return [absolute];
  }));
  return files.flat().sort();
}

async function prepareOutput() {
  if (path.dirname(output) !== artifacts || output === artifacts) {
    throw new Error("Portable output must be a child of the artifacts directory.");
  }
  try {
    const marker = JSON.parse(await readFile(path.join(output, markerName), "utf8"));
    if (marker.generator !== "scripts/build-portable.mjs") {
      throw new Error("Refusing to replace an unrecognized output folder.");
    }
    await rm(output, { recursive: true, force: true });
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
    try {
      await readdir(output);
      throw new Error("Output folder already exists without a generated package marker.");
    } catch (checkError) {
      if (checkError.code !== "ENOENT") throw checkError;
    }
  }
  await mkdir(path.join(output, "assets"), { recursive: true });
  await writeFile(path.join(output, markerName), JSON.stringify({
    generator: "scripts/build-portable.mjs",
    status: "building"
  }, null, 2));
}

async function embedPublicAssets() {
  const publicDirectory = path.join(root, "public");
  const assets = {};
  for (const absolute of await filesWithin(publicDirectory)) {
    const mime = mimeTypes.get(path.extname(absolute).toLowerCase());
    if (!mime) continue;
    const url = `/${path.relative(publicDirectory, absolute).replaceAll(path.sep, "/")}`;
    assets[url] = `data:${mime};base64,${(await readFile(absolute)).toString("base64")}`;
  }
  assets["/start-score-reader.cmd"] = "./start-score-reader.cmd";
  const source = "// Generated by scripts/build-portable.mjs from public/. Do not edit.\n" +
    `globalThis.__MAEUM_PORTABLE_ASSETS__ = ${JSON.stringify(assets, null, 2)};\n`;
  await writeFile(path.join(output, "assets", "public-assets.generated.js"), source);
  return assets;
}

function entryHtml(favicon) {
  return `<!doctype html>
<html lang="ko">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <meta name="theme-color" content="#fffaf2" />
    <link rel="icon" type="image/svg+xml" href="${favicon}" />
    <link rel="stylesheet" href="./assets/app.generated.css" />
    <title>마음멜로디</title>
    <script defer src="./assets/public-assets.generated.js"></script>
    <script defer src="./assets/app.generated.js"></script>
  </head>
  <body>
    <div id="root"></div>
    <noscript>마음멜로디를 실행하려면 브라우저의 JavaScript를 켜 주세요.</noscript>
  </body>
</html>
`;
}

async function copySupportingFiles() {
  const files = [
    [path.join(portableSources, "start-local.cmd"), "전체기능-실행.cmd"],
    [path.join(portableSources, "start-local.ps1"), "start-local.ps1"],
    [path.join(portableSources, "start-score-reader.cmd"), "start-score-reader.cmd"],
    [path.join(portableSources, "instructions.html"), "실행안내.html"],
    [path.join(portableSources, "README.txt"), "읽어주세요.txt"],
    [path.join(root, "public", "homr-helper.generated.mjs"), "homr-helper.generated.mjs"],
    [path.join(root, "THIRD_PARTY_NOTICES.md"), "THIRD_PARTY_NOTICES.md"]
  ];
  for (const [source, name] of files) await cp(source, path.join(output, name));
}

async function archivePackage() {
  const archive = {};
  for (const absolute of await filesWithin(output)) {
    const relative = path.relative(output, absolute).replaceAll(path.sep, "/");
    archive[`${packageName}/${relative}`] = new Uint8Array(await readFile(absolute));
  }
  const zipPath = path.join(artifacts, `${packageName}.zip`);
  const zipped = zipSync(archive, { level: 6 });
  await writeFile(zipPath, zipped);
  return { zipPath, zipBytes: zipped.byteLength };
}

await prepareOutput();
const assets = await embedPublicAssets();
await build({
  root,
  configFile: path.join(root, "vite.config.ts"),
  publicDir: false,
  base: "./",
  define: {
    __PORTABLE_ASSETS__: "globalThis.__MAEUM_PORTABLE_ASSETS__",
    "process.env.NODE_ENV": JSON.stringify("production")
  },
  build: {
    outDir: path.join(output, "assets"),
    emptyOutDir: false,
    cssCodeSplit: false,
    lib: {
      entry: path.join(root, "src", "main.tsx"),
      name: "MaeumMelody",
      formats: ["iife"],
      fileName: () => "app.generated.js",
      cssFileName: "app.generated"
    },
    rollupOptions: { output: { inlineDynamicImports: true } }
  }
});
await writeFile(path.join(output, "index.html"), entryHtml(assets["/favicon.svg"]));
await copySupportingFiles();

const environment = loadEnv("production", root, "VITE_");
const firebaseConfigured = ["API_KEY", "AUTH_DOMAIN", "PROJECT_ID", "APP_ID"]
  .every((key) => Boolean(environment[`VITE_FIREBASE_${key}`]));
if (!firebaseConfigured) throw new Error("Firebase settings are missing; refusing to package a disconnected app.");

const checksums = {};
for (const absolute of await filesWithin(output)) {
  if (path.basename(absolute) === markerName) continue;
  const relative = path.relative(output, absolute).replaceAll(path.sep, "/");
  checksums[relative] = createHash("sha256").update(await readFile(absolute)).digest("hex");
}
await writeFile(path.join(output, markerName), JSON.stringify({
  generator: "scripts/build-portable.mjs",
  builtAt: new Date().toISOString(),
  firebaseConfigured,
  embeddedAssets: Object.keys(assets).length,
  checksums
}, null, 2));
const archive = await archivePackage();
console.log(JSON.stringify({ output, ...archive, embeddedAssets: Object.keys(assets).length }));
